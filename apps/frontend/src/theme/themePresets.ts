/** Apply the asset gate to hydration and every settings write. */
export function enforceAssetAvailability(settings: ThemeSettings): ThemeSettings {
  return {
    ...settings,
    boardPresetId: BOARD_PRESETS[settings.boardPresetId]
      ? settings.boardPresetId : DEFAULT_THEME_SETTINGS.boardPresetId,
    pieceSetId: PIECE_SETS[settings.pieceSetId]?.isAvailable
      ? settings.pieceSetId : DEFAULT_THEME_SETTINGS.pieceSetId,
  }
}
